  await assert.rejects(snapshotCatalogItem(store,'products',gift.id,'2026-09-01'));
  assert.equal((await snapshotCatalogItem(store,'products',gift.id,'2026-09-01',{allowUnavailable:true})).unitCostMinor,0);
